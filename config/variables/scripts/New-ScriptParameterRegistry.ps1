function Protect-AddressText {
    # Help text is copied into the registry. An address in it that is not a documentation, loopback, link-local or fixed Microsoft
    # address is replaced by <address>: the registry never carries an address a deployment chooses.
    param([string]$Text)
    $text = [regex]::Replace($Text, '(?<![\w.])(?:\d{1,3}\.){3}\*', '<address>')
    [regex]::Replace($text, '(?<![\w.])(?<ip>(?:\d{1,3}\.){3}\d{1,3})(?<len>/\d{1,2})?(?!\w|\.\d)', {
            param($m)
            $o = @($m.Groups['ip'].Value.Split('.') | ForEach-Object { [int]$_ })
            if ($o | Where-Object { $_ -gt 255 }) { return $m.Value }
            $documentation = ($o[0] -eq 192 -and $o[1] -eq 0 -and $o[2] -eq 2) -or ($o[0] -eq 198 -and $o[1] -eq 51 -and $o[2] -eq 100) -or ($o[0] -eq 203 -and $o[1] -eq 0 -and $o[2] -eq 113)
            $fixed = $documentation -or $o[0] -in 0, 127 -or ($o[0] -eq 169 -and $o[1] -eq 254) -or $o[0] -eq 255 -or $m.Groups['ip'].Value -in '168.63.129.16', '1.0.0.0'
            if ($fixed) { $m.Value } else { '<address>' }
        })
}

function Get-EnvironmentLikeKind {
    param([string]$Name, [string]$Value)
    if ([string]::IsNullOrWhiteSpace($Value)) { return $null }
    $v = $Value.Trim()
    foreach ($m in [regex]::Matches($v, '(?<![\w.])(?<ip>(?:\d{1,3}\.){3}\d{1,3})(?:/(?<len>\d{1,2}))?(?!\w|\.\d)')) {
        $o = @($m.Groups['ip'].Value.Split('.') | ForEach-Object { [int]$_ })
        if ($o | Where-Object { $_ -gt 255 }) { continue }
        $documentation = ($o[0] -eq 192 -and $o[1] -eq 0 -and $o[2] -eq 2) -or ($o[0] -eq 198 -and $o[1] -eq 51 -and $o[2] -eq 100) -or ($o[0] -eq 203 -and $o[1] -eq 0 -and $o[2] -eq 113)
        $fixed = $documentation -or $o[0] -in 0, 127 -or ($o[0] -eq 169 -and $o[1] -eq 254) -or $o[0] -eq 255 -or $m.Groups['ip'].Value -in '168.63.129.16', '1.0.0.0'
        if (-not $fixed) { return 'IPv4 address' }
    }
    if ($v -match '(?<![0-9a-fA-F-])(?!00000000-0000-0000-0000-000000000000)[0-9a-fA-F]{8}-(?:[0-9a-fA-F]{4}-){3}[0-9a-fA-F]{12}(?![0-9a-fA-F-])') { return 'GUID' }
    if ($script:RegionName.Contains($v)) { return 'Azure region' }
    if ($v -cmatch '^(?:rg|kv|vnet|snet|nsg|log|law|st|vm|nic|pip|lb|vgw|lgw|nat|agw|bas|fw|rt|afw|dcr|dce|acr|aks|appi|iic)-[a-z0-9][a-z0-9-]*$') { return 'resource name' }
    $hostMatch = [regex]::Match($v, '(?<![\w.$-])(?:[a-z0-9_*](?:[a-z0-9_-]*[a-z0-9_])?\.)+(?:com|net|org|io|cloud|local|lan|corp|internal|edu|gov|mil|us|uk|de|info|biz|localdomain|intranet)(?![\w-])', 'IgnoreCase')
    if ($hostMatch.Success) {
        $h = $hostMatch.Value.ToLowerInvariant()
        $allowed = '(^|\.)(improbability\.cloud|example\.(com|net|org)|microsoft\.com|microsoftonline\.com|microsoftonline-p\.com|windows\.net|windowsazure\.com|azure\.com|azure\.net|azure-api\.net|azureedge\.net|azurefd\.net|azurewebsites\.net|trafficmanager\.net|live\.com|office\.com|office365\.com|sharepoint\.com|onmicrosoft\.com|windows\.com|windowsupdate\.com|aka\.ms|visualstudio\.com|powershellgallery\.com|nuget\.org|dot\.net|github\.com|githubusercontent\.com|azurelocal\.cloud|azurelocal\.github\.io)$'
        if ($h -notmatch $allowed) { return 'DNS name' }
    }
    if ($v -match '(?<![\w.])(?:\d{1,3}\.){3}\*') { return 'IPv4 address with a wildcard' }
    if ($v -cmatch '^[A-Za-z]:[\\/]' -and $v -notmatch '^[Cc]:[\\/](Program Files|Windows|Temp|ProgramData|ClusterStorage)') { return 'absolute path on a drive of this machine' }
    if ($v -match '^(REPLACE_|TODO)') { return 'placeholder text instead of a value' }
    if ($Name -match '^(ServicePrincipalName|\w*(Policy|Account|Vault|Workspace|Subscription|Tenant)(Name|Id)|\w*ResourceGroup(Name)?|Region|Location|Hostname|NewHostname|\w*(?-i:IP))$' -and $v -cmatch '^[A-Za-z0-9][A-Za-z0-9_.-]*$') { return 'name or ID of a resource, a subscription, a tenant or a host' }
    if ($Name -match '^(subscription(_?id)?|tenant(_?id)?|resource_?group(_?name)?|(key_?)?vault(_?name)?)$' -and $v -cmatch '^[A-Za-z0-9][A-Za-z0-9_.-]*$' -and $v -notmatch '^[<$@%{]') { return 'value given to a subscription, tenant, resource group or vault parameter' }
    $null
}

