#Requires -Version 7.0
<#
.SYNOPSIS
    Writes the registry entries of the script parameters of this repository, so they are never kept by hand.

.DESCRIPTION
    Every value a person sets is a registered variable, and the registry is the only master. That includes every parameter of every
    script a person calls. This script reads the param() block of each script with the PowerShell parser (the syntax tree: comments
    and strings do not count) and writes one registry group per script, one entry per parameter, between two marker comments in
    tools.arm_deployment.parameters of config/variables/schema/master-registry.yaml. Nothing between the markers is edited by hand.

    Scripts scanned: every .ps1 under scripts/, under ansible/, under tools/ and under pipelines/, and the entry scripts of
    config/variables/scripts. Modules (.psm1), tests and the Claude hooks are not scanned: they are not called by a person.

    Each entry is one JSON-style line, like the hand-written ones (see New_StoragePath_ps1 in the registry): name, type, declared_type
    (as the script writes it), default (as the script writes it; a plain string is stored without its quotes), enum (the ValidateSet
    values), required (Y or N), read_at (the script) and description. The description is the .PARAMETER text of the comment-based help
    when the script has one, with the script name in front, otherwise a neutral sentence built from the parameter name. Nothing else is
    written about what the script does.

    A parameter that a hand-written group of any tool already registers (a group whose area is the script) is left to that group and
    is not written again. A script with all of its parameters registered by hand has no generated group. Generated groups are named
    <script path>_generated, so they never collide with a hand-written group.

    A placeholder script (it ends with exit code 3, NOT IMPLEMENTED) is registered like any other; the group and each description say so.

    A default that looks like an environment value (an address, a name, an ID, a region) is a hard-coded value. The enforcement test
    (tests/variables/Enforcement.Tests.ps1, rule C) fails on those in scripts/ and config/variables/scripts/ (an address with a wildcard,
    placeholder text, a path on a drive, a name given to a resource, policy, account, vault, workspace, subscription, tenant, host or address
    parameter, and the kinds of rule B). This script lists the ones it finds as a warning too, so one in ansible/ or tools/ (which that test
    does not scan) shows up. A test makes sure the two agree. Such a default is not copied into the
    registry (the description says so). Fix it in the script.

    -Check writes nothing and exits 1 when the registry on disk differs from what the scripts say.

.PARAMETER RegistryPath
    The registry. Default: config/variables/schema/master-registry.yaml of this repository.

.PARAMETER Root
    The repository root to scan. Default: the repository this script is in.

.PARAMETER Check
    Compare instead of write. Exit 1 when the registry is out of date.

.PARAMETER PassThru
    Also return one object per script parameter (Script, Parameter, Group, Registration), for the tests.

.OUTPUTS
    With -PassThru: one object per parameter. Otherwise nothing.

.EXAMPLE
    ./config/variables/scripts/New-ScriptParameterRegistry.ps1

.EXAMPLE
    ./config/variables/scripts/New-ScriptParameterRegistry.ps1 -Check
#>
[CmdletBinding()]
param(
    [string]$RegistryPath = (Join-Path $PSScriptRoot '../schema/master-registry.yaml'),
    [string]$Root = (Join-Path $PSScriptRoot '../../..'),
    [switch]$Check,
    [switch]$PassThru
)
