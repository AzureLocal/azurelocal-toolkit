function Get-ScriptFile {
    $list = [System.Collections.Generic.List[string]]::new()
    foreach ($sub in 'scripts', 'ansible', 'tools', 'pipelines') {
        $dir = Join-Path $Root $sub
        if (Test-Path -LiteralPath $dir -PathType Container) {
            foreach ($f in Get-ChildItem -LiteralPath $dir -Recurse -File -Filter '*.ps1') { $list.Add($f.FullName) }
        }
    }
    $own = Join-Path $Root 'config/variables/scripts'
    if (Test-Path -LiteralPath $own -PathType Container) { foreach ($f in Get-ChildItem -LiteralPath $own -File -Filter '*.ps1') { $list.Add($f.FullName) } }
    $sorted = [System.Collections.Generic.SortedDictionary[string, object]]::new([StringComparer]::Ordinal)
    foreach ($full in $list) {
        $relative = [IO.Path]::GetRelativePath($Root, $full).Replace('\', '/')
        $sorted[$relative] = [pscustomobject]@{ Full = $full; Relative = $relative }
    }
    @($sorted.Values)
}

function Get-ConstantText {
    # The value of a constant expression (a number, a string without variables), $null when it is anything else.
    param($Ast)
    if ($Ast -is [System.Management.Automation.Language.StringConstantExpressionAst]) { return $Ast.Value }
    if ($Ast -is [System.Management.Automation.Language.ConstantExpressionAst]) { return $Ast.Extent.Text }
    $null
}

function Get-ScriptParameter {
    # One object per parameter of the script's own param() block.
    param([string]$Full, [string]$Relative)
    $tokens = $null; $errors = $null
    $ast = [System.Management.Automation.Language.Parser]::ParseFile($Full, [ref]$tokens, [ref]$errors)
    # A syntax error inside the param() block makes the parameters unreadable: that is an error. A syntax error elsewhere in the
    # script does not change the param() block (the parser reads it first): the parameters are registered and the script is listed.
    $syntax = $null
    if ($errors -and $errors.Count) {
        $inBlock = $false
        if ($ast.ParamBlock) {
            $from = $ast.ParamBlock.Extent.StartOffset; $to = $ast.ParamBlock.Extent.EndOffset
            foreach ($e in $errors) { if ($e.Extent.StartOffset -ge $from -and $e.Extent.StartOffset -le $to) { $inBlock = $true } }
        }
        else { $inBlock = $true }
        $detail = ($errors | Select-Object -First 3 | ForEach-Object { "line $($_.Extent.StartLineNumber): $(($_.Message -split '\r?\n')[0])" }) -join ' | '
        if ($inBlock) {
            return [pscustomobject]@{ Relative = $Relative; Error = $detail; Syntax = $null; Placeholder = $false; Parameters = @() }
        }
        $syntax = $detail
    }
    $text = [IO.File]::ReadAllText($Full)
    $placeholder = ($text -match '(?m)^#\s*PLACEHOLDER:') -or (($Relative -like 'scripts/deploy/*') -and ($Relative -notlike 'scripts/deploy/common/*') -and ($text -match 'Invoke-Deployment(AzCliPowerShell|Orchestrated|Standalone)\b'))
    $help = $null
    try { $help = $ast.GetHelpContent() } catch { $help = $null }
    $out = [System.Collections.Generic.List[object]]::new()
    if ($ast.ParamBlock) {
        foreach ($p in $ast.ParamBlock.Parameters) {
            $name = $p.Name.VariablePath.UserPath
            $declared = ''
            $enum = $null
            $mandatory = $false
            $setNames = [System.Collections.Generic.List[string]]::new()
            foreach ($attr in $p.Attributes) {
                if ($attr -is [System.Management.Automation.Language.TypeConstraintAst]) { if (-not $declared) { $declared = $attr.TypeName.FullName }; continue }
                if ($attr -isnot [System.Management.Automation.Language.AttributeAst]) { continue }
                $an = $attr.TypeName.Name
                if ($an -ieq 'ValidateSet') {
                    $values = [System.Collections.Generic.List[string]]::new(); $ok = $true
                    foreach ($a in $attr.PositionalArguments) { $v = Get-ConstantText $a; if ($null -eq $v) { $ok = $false; break }; $values.Add([string]$v) }
                    if ($ok -and $values.Count) { $enum = @($values) }
                }
                elseif ($an -ieq 'Parameter') {
                    foreach ($na in $attr.NamedArguments) {
                        if ($na.ArgumentName -ieq 'Mandatory') {
                            $on = $na.ExpressionOmitted -or ($na.Argument.Extent.Text -ieq '$true') -or ($na.Argument.Extent.Text -eq '1')
                            if ($on) {
                                $set = $attr.NamedArguments | Where-Object { $_.ArgumentName -ieq 'ParameterSetName' } | Select-Object -First 1
                                if ($set) { $setNames.Add((Get-ConstantText $set.Argument)) } else { $mandatory = $true }
                            }
                        }
                    }
                }
            }
            $default = $null
            if ($p.DefaultValue) {
                $c = Get-ConstantText $p.DefaultValue
                $default = if ($p.DefaultValue -is [System.Management.Automation.Language.StringConstantExpressionAst]) { [string]$p.DefaultValue.Value } elseif ($null -ne $c) { [string]$c } else { $p.DefaultValue.Extent.Text }
            }
            # A default that spans lines (a multi-line array or script block) is written on one line, so no line ending ends up in a CSV or a table.
            if ($null -ne $default) { $default = ($default -replace '\s*\r?\n\s*', ' ') }
            $helpText = ''
            if ($help -and $help.Parameters -and $help.Parameters.ContainsKey($name.ToUpperInvariant())) {
                $helpText = (($help.Parameters[$name.ToUpperInvariant()] -split '\r?\n' | ForEach-Object { $_.Trim() } | Where-Object { $_ }) -join ' ')
            }
            $out.Add([pscustomobject]@{
                    Name = $name; Declared = $declared; Default = $default; HasDefault = ($null -ne $p.DefaultValue); DefaultIsConstant = ($null -ne $p.DefaultValue -and $null -ne (Get-ConstantText $p.DefaultValue)); Enum = $enum
                    Mandatory = $mandatory; MandatoryInSet = @($setNames); Help = $helpText
                })
        }
    }
    [pscustomobject]@{ Relative = $Relative; Error = $null; Syntax = $syntax; Placeholder = [bool]$placeholder; Parameters = @($out) }
}

