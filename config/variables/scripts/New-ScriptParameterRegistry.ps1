# Build
# ---------------------------------------------------------------------------------------------------------------------------------
$raw = [IO.File]::ReadAllText($RegistryPath)
$eol = if ([regex]::Matches($raw, "`r`n").Count -gt [regex]::Matches($raw, "(?<!`r)`n").Count) { "`r`n" } else { "`n" }   # keep the line endings the file mostly has
$lines = [string[]]($raw -split "`r?`n")
$hadFinalNewline = $lines.Count -gt 0 -and $lines[-1] -eq ''
if ($hadFinalNewline) { $lines = [string[]]$lines[0..($lines.Count - 2)] }
$split = Split-RegistryText -Lines $lines
$hand = Get-HandWritten -Lines @($split.Head + $split.Tail)

$scripts = @(Get-ScriptFile)
$block = [System.Collections.Generic.List[string]]::new()
$records = [System.Collections.Generic.List[object]]::new()
$problems = [System.Collections.Generic.List[string]]::new()
$groupKeys = @{}
$scanned = 0
$withParameters = 0
$registered = 0

foreach ($file in $scripts) {
    $scanned++
    $info = Get-ScriptParameter -Full $file.Full -Relative $file.Relative
    if ($info.Error) { $problems.Add("$($file.Relative): the script does not parse: $($info.Error)"); continue }
    if ($info.Syntax) { Write-Warning "$($file.Relative): the script has a syntax error outside its param() block ($($info.Syntax)). Its parameters are registered. Fix the script." }
    if (-not $info.Parameters.Count) { continue }
    $withParameters++
    $known = if ($hand.ContainsKey($file.Relative)) { $hand[$file.Relative] } else { $null }
    $group = ConvertTo-GroupKey $file.Relative
    if ($groupKeys.ContainsKey($group)) { throw "Two scripts give the group name '$group': $($groupKeys[$group]) and $($file.Relative)." }
    $groupKeys[$group] = $file.Relative
    $leaf = [System.Collections.Generic.List[string]]::new()
    $fileName = [IO.Path]::GetFileName($file.Relative)
    foreach ($p in $info.Parameters) {
        $kind = $null
        if ($p.HasDefault -and $p.DefaultIsConstant) {
            $kind = Get-EnvironmentLikeKind -Name $p.Name -Value ([string]$p.Default)
            if ($kind) { Write-Warning "$($file.Relative): -$($p.Name) defaults to '$($p.Default)', which looks like an environment value ($kind). Read it from the infrastructure file instead." }
        }
        if ($known -and $known.Contains($p.Name)) {
            $records.Add([pscustomobject]@{ Script = $file.Relative; Parameter = $p.Name; Group = $null; Registration = 'hand-written' })
            continue
        }
        $registered++
        $declared = $p.Declared
        $type = Get-RegistryType $declared
        $parts = [System.Collections.Generic.List[string]]::new()
        $parts.Add('"name":' + (ConvertTo-JsonText $p.Name))
        $parts.Add('"type":' + (ConvertTo-JsonText $type))
        $parts.Add('"declared_type":' + (ConvertTo-JsonText $declared))
        # A default that looks like an environment value is not copied into the registry: the registry must not carry a value a deployment chooses.
        if ($p.HasDefault -and -not $kind) {
            $parts.Add('"default":' + (ConvertTo-JsonText ([string]$p.Default)))
        }
        if ($p.Enum) { $parts.Add('"enum":[' + (($p.Enum | ForEach-Object { ConvertTo-JsonText $_ }) -join ',') + ']') }
        $parts.Add('"required":' + (ConvertTo-JsonText $(if ($p.Mandatory) { 'Y' } else { 'N' })))
        $parts.Add('"read_at":' + (ConvertTo-JsonText $file.Relative))
        $desc = $fileName + '. '
        if ($info.Placeholder) { $desc += 'Placeholder script: it ends with exit code 3 (NOT IMPLEMENTED). ' }
        $desc += $(if ($p.Help) { Protect-AddressText $p.Help } else { Get-NeutralDescription -Name $p.Name -DeclaredType $declared })
        if ($kind) { $desc += " The default in the script looks like an environment value ($kind) and is not registered here; the script should read it from the infrastructure file." }
        if ($p.MandatoryInSet.Count) { $desc += " Required in the parameter set $(($p.MandatoryInSet | Sort-Object -Unique) -join ', ')." }
        $parts.Add('"description":' + (ConvertTo-JsonText $desc))
        $leaf.Add("                $(ConvertTo-PropertyKey $p.Name): {" + ($parts -join ',') + '}')
        $records.Add([pscustomobject]@{ Script = $file.Relative; Parameter = $p.Name; Group = $group; Registration = 'generated' })
    }
    if (-not $leaf.Count) { continue }
    $block.Add("$($Indent)${group}:")
    $block.Add("$Indent  type: object")
    $block.Add("$Indent  area: $(ConvertTo-JsonText $file.Relative)")
    if ($info.Placeholder) { $block.Add("$Indent  description: $(ConvertTo-JsonText 'Placeholder script: it ends with exit code 3 (NOT IMPLEMENTED) and changes nothing. Its parameters are registered as declared.')") }
    $block.Add("$Indent  properties:")
    foreach ($l in $leaf) { $block.Add($l) }
}

if ($problems.Count) {
    foreach ($problem in $problems) { Write-Error $problem -ErrorAction Continue }
}

$newLines = [System.Collections.Generic.List[string]]::new()
$newLines.AddRange([string[]]$split.Head)
$newLines.Add("$Indent$BeginMarker")
$newLines.AddRange($block)
$newLines.Add("$Indent$EndMarker")
$newLines.AddRange([string[]]$split.Tail)
$newText = ($newLines -join $eol) + $(if ($hadFinalNewline) { $eol } else { '' })

$stale = $raw -cne $newText
$summary = "$scanned scripts scanned, $withParameters with parameters, $registered parameters in the generated block, $($records.Count - $registered) registered by hand elsewhere."

if ($Check) {
    if ($problems.Count) { Write-Host "Script parameter registry: $($problems.Count) script(s) did not parse."; exit 1 }
    if ($stale) { Write-Error "$RegistryPath is out of date. Run ./config/variables/scripts/New-ScriptParameterRegistry.ps1" -ErrorAction Continue; exit 1 }
    Write-Host "$RegistryPath is current. $summary"
}
else {
    if ($problems.Count) { Write-Host 'Nothing written: fix the scripts that do not parse first.'; exit 1 }
    if ($stale) { [IO.File]::WriteAllText($RegistryPath, $newText, [Text.UTF8Encoding]::new($false)); Write-Host "Wrote $RegistryPath. $summary" }
    else { Write-Host "$RegistryPath already current. $summary" }
}
if ($PassThru) { $records }
