function Split-RegistryText {
    # Returns the text before the begin marker, the text after the end marker, and whether the markers exist. Without markers the
    # block goes before the line that follows tools.arm_deployment.parameters.
    param([string[]]$Lines)
    $begin = -1; $end = -1
    for ($i = 0; $i -lt $Lines.Count; $i++) {
        if ($begin -lt 0 -and $Lines[$i].Trim() -eq $BeginMarker) { $begin = $i }
        elseif ($Lines[$i].Trim() -eq $EndMarker) { $end = $i }
    }
    if ($begin -ge 0 -and $end -gt $begin) {
        return [pscustomobject]@{ Head = @($Lines[0..($begin - 1)]); Tail = $(if ($end + 1 -lt $Lines.Count) { @($Lines[($end + 1)..($Lines.Count - 1)]) } else { @() }); Found = $true }
    }
    if ($begin -ge 0 -or $end -ge 0) { throw "$RegistryPath has one of the two markers of the script parameters but not both, in order." }
    $tools = [array]::IndexOf($Lines, 'tools:')
    if ($tools -lt 0) { throw "$RegistryPath has no top-level 'tools:' section." }
    $armLine = -1
    for ($i = $tools + 1; $i -lt $Lines.Count; $i++) { if ($Lines[$i] -match '^    arm_deployment:\s*$') { $armLine = $i; break } }
    if ($armLine -lt 0) { throw "$RegistryPath has no tools.$Tool section." }
    $paramLine = -1
    for ($i = $armLine + 1; $i -lt $Lines.Count; $i++) { if ($Lines[$i] -match '^        parameters:\s*$') { $paramLine = $i; break } if ($Lines[$i] -match '^    \S') { break } }
    if ($paramLine -lt 0) { throw "$RegistryPath has no tools.$Tool.parameters section." }
    $next = $Lines.Count
    for ($i = $paramLine + 1; $i -lt $Lines.Count; $i++) { if ($Lines[$i] -match '^        \S' -or $Lines[$i] -match '^    \S' -or $Lines[$i] -match '^\S') { $next = $i; break } }
    [pscustomobject]@{ Head = @($Lines[0..($next - 1)]); Tail = @($Lines[$next..($Lines.Count - 1)]); Found = $false }
}

function Get-HandWritten {
    # The parameters that groups of tools.*.parameters outside the markers register for a script of this repository.
    # Returns a hashtable: script path -> set of parameter names.
    param([string[]]$Lines)
    $toolsAt = [array]::IndexOf($Lines, 'tools:')
    $end = $Lines.Count
    for ($i = $toolsAt + 1; $i -lt $Lines.Count; $i++) { if ($Lines[$i] -match '^\S') { $end = $i; break } }
    $tmp = Join-Path ([IO.Path]::GetTempPath()) ('azl-tools-' + [guid]::NewGuid().ToString('N') + '.yaml')
    try {
        [IO.File]::WriteAllLines($tmp, [string[]]$Lines[$toolsAt..($end - 1)], [Text.UTF8Encoding]::new($false))
        $node = Read-RegistryYaml -Path $tmp
    }
    finally { Remove-Item -LiteralPath $tmp -ErrorAction SilentlyContinue }
    $result = @{}
    foreach ($toolName in @($node['tools']['properties'].Keys)) {
        $toolNode = $node['tools']['properties'][$toolName]
        if ($toolNode -isnot [System.Collections.IDictionary] -or -not $toolNode.Contains('properties') -or -not $toolNode['properties'].Contains('parameters')) { continue }
        $parameters = $toolNode['properties']['parameters']
        if (-not $parameters.Contains('properties')) { continue }
        foreach ($group in $parameters['properties'].Values) {
            if ($group -isnot [System.Collections.IDictionary] -or -not $group.Contains('area')) { continue }
            $area = [string]$group['area']
            foreach ($candidate in $area, "scripts/$area") {
                if (-not $result.ContainsKey($candidate)) { $result[$candidate] = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal) }
                if ($group.Contains('properties')) {
                    foreach ($child in $group['properties'].Values) {
                        if ($child -is [System.Collections.IDictionary] -and $child.Contains('name')) { [void]$result[$candidate].Add([string]$child['name']) }
                    }
                }
            }
        }
    }
    $result
}

