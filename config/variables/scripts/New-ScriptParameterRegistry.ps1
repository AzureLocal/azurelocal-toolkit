function ConvertTo-JsonText {
    # A JSON string with every non-ASCII character escaped, so the registry stays ASCII where this script writes.
    param([string]$Text)
    $sb = [System.Text.StringBuilder]::new()
    [void]$sb.Append('"')
    foreach ($c in $Text.ToCharArray()) {
        $n = [int]$c
        if ($c -eq '"') { [void]$sb.Append('\"') }
        elseif ($c -eq '\') { [void]$sb.Append('\\') }
        elseif ($n -eq 10) { [void]$sb.Append('\n') }
        elseif ($n -eq 13) { [void]$sb.Append('\r') }
        elseif ($n -eq 9) { [void]$sb.Append('\t') }
        elseif ($n -lt 32 -or $n -gt 126) { [void]$sb.Append(('\u{0:x4}' -f $n)) }
        else { [void]$sb.Append($c) }
    }
    [void]$sb.Append('"')
    $sb.ToString()
}

function ConvertTo-GroupKey {
    param([string]$RelativePath)
    ($RelativePath -replace '[^A-Za-z0-9]', '_') + '_generated'
}

function ConvertTo-PropertyKey {
    # The parameter name as a YAML key. A name YAML 1.1 reads as something else (yes, no, on, off, a number) is quoted.
    param([string]$Name)
    if ($Name -match '^(y|n|yes|no|on|off|true|false|null|~)$' -or $Name -match '^[0-9]') { return (ConvertTo-JsonText $Name) }
    $Name
}

function Get-NeutralDescription {
    param([string]$Name, [string]$DeclaredType)
    $words = ($Name -creplace '([a-z0-9])([A-Z])', '$1 $2' -creplace '([A-Z]+)([A-Z][a-z])', '$1 $2').ToLowerInvariant()
    $words = $words.Substring(0, 1).ToUpperInvariant() + $words.Substring(1)
    if ($DeclaredType -ieq 'switch') { return "$words switch (no help text for this parameter)." }
    "$words (no help text for this parameter)."
}

function Get-RegistryType {
    param([string]$DeclaredType)
    $t = $DeclaredType.Trim().ToLowerInvariant()
    if (-not $t) { return 'object' }
    if ($t.EndsWith(']') -and $t.Contains('[')) {
        if ($t -match '^[^\[]+\[\]$') { return 'array' }
        if ($t -match '^system\.collections\.generic\.(list|hashset)\[') { return 'array' }
        if ($t -match '^system\.collections\.generic\.(dictionary|idictionary)\[') { return 'object' }
        return 'array'
    }
    $short = $t -replace '^system\.(management\.automation\.|collections\.|io\.|net\.)?', ''
    switch -Regex ($short) {
        '^(string|char|securestring|pscredential|datetime|timespan|uri|guid|version|ipaddress|fileinfo|directoryinfo|regex|mailaddress)$' { return 'string' }
        '^(switch|bool|boolean)$' { return 'boolean' }
        '^(int|int16|int32|int64|long|short|byte|sbyte|uint16|uint32|uint64|ulong|ushort)$' { return 'integer' }
        '^(double|single|float|decimal)$' { return 'number' }
        default { return 'object' }
    }
}

